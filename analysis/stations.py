def strip_suffix(name: str) -> str:
    """'정선군' → '정선', '김해시' → '김해'. 두 글자 이하 이름은 그대로 둔다."""
    return name[:-1] if len(name) > 2 and name[-1] in "시군구" else name


def map_stations(parent_regions: dict) -> tuple[dict, list]:
    """관측소 → 시군구코드. parent_regions: {코드: 이름}(하위 구를 뺀 시군구).

    반환: ({시군구코드: 지점번호}, 자동 매칭이 안 된 관측소 목록)
    """
    by_stripped = {}
    for code, name in parent_regions.items():
        by_stripped.setdefault(strip_suffix(name), []).append(code)

    result, unmatched = {}, []
    for stn, name in STATIONS.items():
        if stn in MANUAL:
            code = MANUAL[stn]
        else:
            cands = by_stripped.get(strip_suffix(name), [])
            code = cands[0] if len(cands) == 1 else None
            if code is None:
                unmatched.append((stn, name, cands))
        if code and code in parent_regions:
            result.setdefault(code, stn)
    return result, unmatched
